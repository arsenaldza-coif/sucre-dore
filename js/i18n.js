/* ------------------- Gestion de la langue ------------------- */

let currentLang = localStorage.getItem("scd_lang") || "fr";
if (!I18N[currentLang]) currentLang = "fr";

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.fr[key] || key;
}

function getLang() { return currentLang; }

function setLang(lang) {
  currentLang = I18N[lang] ? lang : "fr";
  localStorage.setItem("scd_lang", currentLang);

  const html = document.documentElement;
  html.lang = lang === "ar" ? "ar" : "fr";
  html.dir = lang === "ar" ? "rtl" : "ltr";

  // Textes statiques [data-i18n]
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  // Placeholders [data-i18n-placeholder]
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.title = t("site_title");

  // Prévenir les autres modules (re-rendu du contenu dynamique)
  document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
}
